func TestGenerateCreatesActionRegisterAndRunner(t *testing.T) {
	root := newTestProject(t, "example.com/acme")
	writeTestApp(t, root, "sales")
	writeTestEntity(t, root, "sales", "lead")

	result, err := Generate(root, "sales", "lead")
	if err != nil {
		t.Fatalf("Generate() error = %v, want nil", err)
	}
	if !result.ActionFileCreated || !result.RunnerFileWritten {
		t.Fatalf("Generate() result = %+v, want created/written files", result)
	}

	actionSource := readTestFile(t, filepath.Join(root, "apps", "sales", "entities", "lead", "actions", "actions.go"))
	if strings.Contains(actionSource, "DO NOT EDIT") || strings.Contains(actionSource, "Code generated by dygo") {
		t.Fatalf("action source = %q, want developer-owned starter without generated ownership header", actionSource)
	}
	for _, want := range []string{
		"package actions",
		"func Register(registry dygo.EntityActionRegistry) error",
		`Name:      "lead-action"`,
		`Label:     "Lead Action"`,
		"Selection: dygo.ActionSelectionRecord",
		"func runLeadAction(ctx context.Context, call dygo.EntityActionCall) (any, error)",
		"TODO(sales/lead): implement action behavior",
	} {
		if !strings.Contains(actionSource, want) {
			t.Fatalf("action source = %q, want substring %q", actionSource, want)
		}
	}

	runnerSource := readTestFile(t, filepath.Join(root, "cmd", "dygo", "main.go"))
	for _, want := range []string{
		runnergen.GeneratedHeader,
		`salesleadactions "example.com/acme/apps/sales/entities/lead/actions"`,
		"EntityActions: []dygo.EntityActionRegistrar{",
		"salesleadactions.Register",
	} {
		if !strings.Contains(runnerSource, want) {
			t.Fatalf("runner source = %q, want substring %q", runnerSource, want)
		}
	}

	second, err := Generate(root, "sales", "lead")
	if err != nil {
		t.Fatalf("Generate() second error = %v, want nil", err)
	}
	if second.ActionFileCreated || second.RunnerFileWritten {
		t.Fatalf("Generate() second result = %+v, want idempotent no-op", second)
	}
}

