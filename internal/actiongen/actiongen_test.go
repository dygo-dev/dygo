func TestHookSyncRemovesDeletedActionWiring(t *testing.T) {
	root := newTestProject(t, "example.com/acme")
	writeTestApp(t, root, "sales")
	writeTestEntity(t, root, "sales", "lead")

	if _, err := Generate(root, "sales", "lead"); err != nil {
		t.Fatalf("Generate(action) error = %v, want nil", err)
	}
	if _, err := hookgen.Generate(root, "sales", "lead"); err != nil {
		t.Fatalf("Generate(hook) error = %v, want nil", err)
	}
	if err := os.Remove(filepath.Join(root, "apps", "sales", "entities", "lead", "actions", "actions.go")); err != nil {
		t.Fatalf("Remove(actions.go) error = %v", err)
	}

	if _, written, err := hookgen.UpdateRunner(root); err != nil {
		t.Fatalf("UpdateRunner() error = %v, want nil", err)
	} else if !written {
		t.Fatal("UpdateRunner() written = false, want runner update after action removal")
	}

	runnerSource := readTestFile(t, filepath.Join(root, "cmd", "dygo", "main.go"))
	if strings.Contains(runnerSource, "salesleadactions") || strings.Contains(runnerSource, "EntityActions:") {
		t.Fatalf("runner source = %q, want deleted action wiring removed", runnerSource)
	}
	if !strings.Contains(runnerSource, "salesleadhooks.Register") {
		t.Fatalf("runner source = %q, want remaining hook wiring", runnerSource)
	}
}

